using System.Globalization;
using System.Net;
using System.Text;
using System.Text.Json;
using System.Text.Json.Serialization;
using System.Text.RegularExpressions;
using BPM.Core.Analysis;
using BPM.Core.Models;

namespace BPM.Core.Reports;

/// <summary>Output format of an exported report.</summary>
public enum ReportFormat { Html, Csv, Json }

/// <summary>Turns a <see cref="ScanResult"/> into a shareable HTML, CSV or JSON report. Read-only; never touches browser data.</summary>
public static partial class ReportExporter
{
    private const string Footer = "Generated by Browser Profile Manager. Read-only scan: no cookies, passwords or history were read.";

    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        WriteIndented = true,
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        Converters = { new JsonStringEnumConverter(JsonNamingPolicy.CamelCase) },
    };

    [GeneratedRegex(@"[^\s@<>""',;()\[\]]+@[^\s@<>""',;()\[\]]+")]
    private static partial Regex EmailPattern();

    /// <summary>Writes the report to <paramref name="path"/> in the given format (UTF-8; CSV with BOM so Excel reads it).</summary>
    public static void Export(ScanResult scan, IReadOnlyList<Problem> problems, string path, ReportFormat format, bool hideEmails)
    {
        var text = format switch
        {
            ReportFormat.Html => BuildHtml(scan, problems, hideEmails),
            ReportFormat.Csv => BuildCsv(scan, hideEmails),
            ReportFormat.Json => BuildJson(scan, problems, hideEmails),
            _ => throw new ArgumentOutOfRangeException(nameof(format)),
        };
        var dir = Path.GetDirectoryName(Path.GetFullPath(path));
        if (!string.IsNullOrEmpty(dir)) Directory.CreateDirectory(dir);
        File.WriteAllText(path, text, new UTF8Encoding(encoderShouldEmitUTF8Identifier: format == ReportFormat.Csv));
    }

    /// <summary>"sam.lee@example.com" becomes "s***@example.com"; null/empty gives null; text without '@' gives "***".</summary>
    public static string? MaskEmail(string? email)
    {
        if (string.IsNullOrEmpty(email)) return null;
        var at = email.IndexOf('@');
        if (at < 0) return "***";
        return (at > 0 ? email[..1] : "") + "***" + email[at..];
    }

    /// <summary>File name like "BrowserProfileReport_OFFICE-PC_20261029-1930.html".</summary>
    public static string SuggestedFileName(ScanResult scan, ReportFormat format)
    {
        var ext = format switch { ReportFormat.Html => "html", ReportFormat.Csv => "csv", _ => "json" };
        var machine = string.Concat(scan.MachineName.Select(c => char.IsLetterOrDigit(c) || c is '-' or '_' ? c : '_'));
        return $"BrowserProfileReport_{machine}_{scan.ScannedAt.ToString("yyyyMMdd-HHmm", CultureInfo.InvariantCulture)}.{ext}";
    }

    // ---------- shared helpers ----------

    /// <summary>Masks every email-looking token inside free text when hiding is on.</summary>
    private static string Txt(string? text, bool hide)
    {
        if (string.IsNullOrEmpty(text)) return "";
        return hide ? EmailPattern().Replace(text, m => MaskEmail(m.Value)!) : text;
    }

    private static string? TxtOrNull(string? text, bool hide) => string.IsNullOrEmpty(text) ? null : Txt(text, hide);

    private static string Join(IEnumerable<string> items, bool hide) => string.Join("; ", items.Select(i => Txt(i, hide)));

    private static string SourceText(ExtensionSource s) => s switch
    {
        ExtensionSource.Store => "Store",
        ExtensionSource.Developer => "Developer",
        ExtensionSource.OtherProgram => "Another program",
        ExtensionSource.Policy => "Policy",
        ExtensionSource.Preinstalled => "Pre-installed",
        _ => "Unknown",
    };

    private static string Date(DateTime? d) => d?.ToString("yyyy-MM-dd", CultureInfo.InvariantCulture) ?? "";

    // ---------- CSV ----------

    /// <summary>One row per extension per profile (profiles without extensions get one row with empty extension columns).</summary>
    public static string BuildCsv(ScanResult scan, bool hideEmails)
    {
        var sb = new StringBuilder();
        AppendRow(sb, ["Browser", "Profile", "Profile email", "Extension", "Extension ID", "Version", "State", "Why off",
            "Installed from", "Risk", "Risk reasons", "Manifest version", "Installed"]);
        foreach (var browser in scan.Browsers)
        foreach (var profile in browser.Profiles)
        {
            var head = new[] { Txt(browser.Name, hideEmails), Txt(profile.Name, hideEmails), hideEmails ? MaskEmail(profile.Email) ?? "" : profile.Email ?? "" };
            if (profile.Extensions.Count == 0)
            {
                AppendRow(sb, [.. head, "", "", "", "", "", "", "", "", "", ""]);
                continue;
            }
            foreach (var e in profile.Extensions)
                AppendRow(sb, [.. head, Txt(e.Name, hideEmails), e.Id, e.Version, e.Enabled ? "On" : "Off",
                    Join(e.DisableReasons, hideEmails), SourceText(e.Source), e.Risk.Level.ToString(),
                    Join(e.Risk.Reasons, hideEmails), e.ManifestVersion > 0 ? e.ManifestVersion.ToString(CultureInfo.InvariantCulture) : "",
                    Date(e.InstalledAt)]);
        }
        return sb.ToString();
    }

    private static void AppendRow(StringBuilder sb, string[] fields)
    {
        sb.AppendJoin(',', fields.Select(CsvField)).Append("\r\n");
    }

    private static string CsvField(string? value)
    {
        if (string.IsNullOrEmpty(value)) return "";
        return value.AsSpan().IndexOfAny(",\"\r\n") >= 0 ? "\"" + value.Replace("\"", "\"\"") + "\"" : value;
    }

    // ---------- JSON ----------

    /// <summary>Indented, camelCase JSON built from plain anonymous objects (the model classes are never serialized directly).</summary>
    public static string BuildJson(ScanResult scan, IReadOnlyList<Problem> problems, bool hideEmails)
    {
        var doc = new
        {
            generatedAt = scan.ScannedAt,
            machine = Txt(scan.MachineName, hideEmails),
            user = Txt(scan.UserName, hideEmails),
            summary = new
            {
                browsers = scan.Browsers.Count,
                profiles = scan.AllProfiles.Count(),
                extensions = scan.AllExtensions.Count(),
                enabled = scan.AllExtensions.Count(e => e.Enabled),
                highRisk = scan.AllExtensions.Count(e => e.Risk.Level == RiskLevel.High),
                waitingForApproval = scan.AllExtensions.Count(e => e.NeedsApproval),
            },
            problems = problems.Select(p => new { severity = p.Severity, title = Txt(p.Title, hideEmails), detail = Txt(p.Detail, hideEmails) }),
            browsers = scan.Browsers.Select(b => new
            {
                name = Txt(b.Name, hideEmails),
                version = b.Version,
                exePath = TxtOrNull(b.ExePath, hideEmails),
                dataDir = TxtOrNull(b.DataDir, hideEmails),
                profiles = b.Profiles.Select(p => new
                {
                    name = Txt(p.Name, hideEmails),
                    email = hideEmails ? MaskEmail(p.Email) : p.Email,
                    folder = Txt(p.Key, hideEmails),
                    isOpen = p.IsOpen,
                    lastActive = p.LastActive,
                    extensions = p.Extensions.Select(e => new
                    {
                        name = Txt(e.Name, hideEmails),
                        id = e.Id,
                        version = e.Version,
                        enabled = e.Enabled,
                        reasons = e.DisableReasons.Select(r => Txt(r, hideEmails)).ToArray(),
                        source = e.Source,
                        risk = e.Risk.Level,
                        riskReasons = e.Risk.Reasons.Select(r => Txt(r, hideEmails)).ToArray(),
                        manifestVersion = e.ManifestVersion,
                        installedAt = e.InstalledAt,
                        apiPermissions = e.ApiPermissions,
                        hostPermissions = e.HostPermissions,
                        storeUrl = e.StoreUrl,
                    }).ToArray(),
                }).ToArray(),
            }).ToArray(),
        };
        return JsonSerializer.Serialize(doc, JsonOptions);
    }

    // ---------- HTML ----------

    private static string H(string? text, bool hide) => WebUtility.HtmlEncode(Txt(text, hide));

    /// <summary>One self-contained page: inline CSS, no scripts, light and dark aware.</summary>
    public static string BuildHtml(ScanResult scan, IReadOnlyList<Problem> problems, bool hideEmails)
    {
        var sb = new StringBuilder(16 * 1024);
        sb.Append("<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n")
          .Append("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n")
          .Append("<title>Browser Profile Manager report</title>\n<style>\n").Append(Css).Append("</style>\n</head>\n<body>\n<main>\n");

        sb.Append("<h1>Browser Profile Manager report</h1>\n<p class=\"meta\">")
          .Append("Machine: ").Append(H(scan.MachineName, hideEmails))
          .Append(" &middot; User: ").Append(H(scan.UserName, hideEmails))
          .Append(" &middot; Scanned: ").Append(WebUtility.HtmlEncode(scan.ScannedAt.ToString("yyyy-MM-dd HH:mm", CultureInfo.InvariantCulture)))
          .Append("</p>\n");

        var exts = scan.AllExtensions.ToList();
        sb.Append("<div class=\"cards\">");
        Counter(sb, scan.Browsers.Count, "Browsers");
        Counter(sb, scan.AllProfiles.Count(), "Profiles");
        Counter(sb, exts.Count, "Extensions");
        Counter(sb, exts.Count(e => e.Enabled), "Enabled");
        Counter(sb, exts.Count(e => e.Risk.Level == RiskLevel.High), "High risk");
        Counter(sb, exts.Count(e => e.NeedsApproval), "Waiting for approval");
        sb.Append("</div>\n");

        sb.Append("<h2>Problems found</h2>\n");
        if (problems.Count == 0) sb.Append("<p class=\"muted\">No problems found.</p>\n");
        else
        {
            sb.Append("<ul class=\"problems\">\n");
            foreach (var p in problems)
            {
                var cls = p.Severity.ToString().ToLowerInvariant();
                sb.Append("<li class=\"").Append(cls).Append("\"><strong>").Append(H(p.Title, hideEmails)).Append("</strong>")
                  .Append(" <span class=\"sev\">").Append(WebUtility.HtmlEncode(p.Severity.ToString())).Append("</span><br>")
                  .Append(H(p.Detail, hideEmails)).Append("</li>\n");
            }
            sb.Append("</ul>\n");
        }

        foreach (var b in scan.Browsers)
        {
            sb.Append("<h2>").Append(H(b.Name, hideEmails));
            if (!string.IsNullOrEmpty(b.Version)) sb.Append(" <span class=\"ver\">").Append(H(b.Version, hideEmails)).Append("</span>");
            sb.Append("</h2>\n");
            foreach (var p in b.Profiles)
            {
                sb.Append("<h3>").Append(H(p.Name, hideEmails));
                var email = hideEmails ? MaskEmail(p.Email) : p.Email;
                if (!string.IsNullOrEmpty(email)) sb.Append(" <span class=\"email\">").Append(WebUtility.HtmlEncode(email)).Append("</span>");
                sb.Append(" <span class=\"folder\">").Append(H(p.Key, hideEmails)).Append("</span>");
                if (p.IsOpen) sb.Append(" <span class=\"badge open\">open</span>");
                sb.Append("</h3>\n");
                if (p.Extensions.Count == 0) { sb.Append("<p class=\"muted\">No extensions.</p>\n"); continue; }

                sb.Append("<div class=\"wrap\"><table>\n<thead><tr><th>Extension</th><th>Version</th><th>State</th><th>Installed from</th><th>Risk</th></tr></thead>\n<tbody>\n");
                foreach (var e in p.Extensions)
                {
                    sb.Append("<tr><td>");
                    var name = H(e.Name, hideEmails);
                    if (e.StoreUrl is { Length: > 0 } url && Uri.TryCreate(url, UriKind.Absolute, out var uri) && uri.Scheme is "http" or "https")
                        sb.Append("<a href=\"").Append(WebUtility.HtmlEncode(uri.AbsoluteUri)).Append("\" rel=\"noreferrer\">").Append(name).Append("</a>");
                    else sb.Append(name);
                    sb.Append("</td><td>").Append(H(e.Version, hideEmails)).Append("</td><td>");
                    sb.Append(e.Enabled ? "<span class=\"on\">On</span>" : "<span class=\"off\">Off</span>");
                    if (e.DisableReasons.Count > 0) sb.Append("<br><small>").Append(WebUtility.HtmlEncode(Join(e.DisableReasons, hideEmails))).Append("</small>");
                    sb.Append("</td><td>").Append(SourceText(e.Source)).Append("</td><td>");
                    var title = e.Risk.Reasons.Count > 0 ? $" title=\"{WebUtility.HtmlEncode(Join(e.Risk.Reasons, hideEmails))}\"" : "";
                    sb.Append("<span class=\"badge risk-").Append(e.Risk.Level.ToString().ToLowerInvariant()).Append('"').Append(title).Append('>')
                      .Append(e.Risk.Level).Append("</span></td></tr>\n");
                }
                sb.Append("</tbody></table></div>\n");
            }
        }

        sb.Append("<footer>").Append(Footer).Append("</footer>\n</main>\n</body>\n</html>\n");
        return sb.ToString();
    }

    private static void Counter(StringBuilder sb, int value, string label) =>
        sb.Append("<div class=\"card\"><b>").Append(value.ToString(CultureInfo.InvariantCulture)).Append("</b><span>").Append(label).Append("</span></div>");

